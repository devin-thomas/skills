#!/usr/bin/env python3
"""Audit a React project for hand-built UI components that an established library covers.

Read-only. Standard library only. Reads package.json, optional components.json and
source files under src/, app/, components/ and pages/; it never installs or runs
project code. Prints one JSON document.

    python ui_library_audit.py PROJECT_DIR [--max-files 2000]

Exit codes: 0 audit produced (findings may be empty), 2 not a usable project.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SOURCE_DIRS = ("src", "app", "components", "pages")
SOURCE_SUFFIXES = {".ts", ".tsx", ".js", ".jsx"}
SKIP_PARTS = {"node_modules", ".next", "dist", "build", ".git", "coverage"}
# Files generated by a library's own CLI are the library, not a hand-rolled copy.
VENDORED_DIR_HINT = ("components", "ui")

# task -> (tier, preferred package, hand-rolled name patterns, competitor packages)
TASKS: dict[str, dict] = {
    "toast": {
        "tier": "specialist",
        "preferred": ["sonner"],
        "recommend": "Sonner (shadcn registry item: sonner)",
        "name_pattern": r"\b(?:function|const|class)\s+(?:Toast\w*|Snackbar\w*|Notification(?:Stack|Center)\w*)\b",
        "competitors": ["react-hot-toast", "react-toastify", "notistack", "@radix-ui/react-toast"],
    },
    "drawer": {
        "tier": "specialist",
        "preferred": ["vaul"],
        "recommend": "Vaul drawer (shadcn registry item: drawer); check maintenance first",
        "name_pattern": r"\b(?:function|const|class)\s+(?:Drawer\w*|BottomSheet\w*|SlideUp\w*)\b",
        "competitors": ["react-modal-sheet", "react-spring-bottom-sheet", "@gorhom/bottom-sheet"],
    },
    "command-menu": {
        "tier": "specialist",
        "preferred": ["cmdk"],
        "recommend": "cmdk (shadcn registry item: command)",
        "name_pattern": r"\b(?:function|const|class)\s+(?:Command(?:Palette|Menu|K)\w*|CmdK\w*|QuickSwitcher\w*)\b",
        "competitors": ["kbar", "react-cmdk"],
    },
    "animated-number": {
        "tier": "specialist",
        "preferred": ["@number-flow/react"],
        "recommend": "NumberFlow (@number-flow/react)",
        "name_pattern": r"\b(?:function|const|class)\s+(?:Animated(?:Number|Counter)\w*|CountUp\w*|TickingNumber\w*)\b",
        "competitors": ["react-countup", "react-animated-numbers"],
    },
    "dialog-menu-popover": {
        "tier": "foundation",
        "preferred": ["@base-ui/react", "@base-ui-components/react", "radix-ui"],
        "preferred_prefixes": ["@radix-ui/react-"],
        "recommend": "the project's foundation (shadcn dialog/dropdown-menu/popover, Base UI, or Radix)",
        "name_pattern": r"""role\s*=\s*["'](?:dialog|alertdialog|menu|listbox)["']""",
        "competitors": ["react-modal", "reactjs-popup", "@headlessui/react", "react-aria-components"],
    },
}


def load_json(path: Path) -> dict | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def source_files(root: Path, limit: int) -> list[Path]:
    found: list[Path] = []
    for name in SOURCE_DIRS:
        base = root / name
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*")):
            if len(found) >= limit:
                return found
            if path.suffix in SOURCE_SUFFIXES and not (SKIP_PARTS & set(path.parts)):
                found.append(path)
    return found


def is_vendored(rel: Path, installed_ui_dir: str | None) -> bool:
    """A file inside the shadcn-style ui directory is library-owned code, not a hand-roll."""
    if installed_ui_dir and rel.as_posix().startswith(installed_ui_dir.rstrip("/") + "/"):
        return True
    return tuple(rel.parts[-3:-1]) == VENDORED_DIR_HINT or tuple(rel.parts[-2:-1]) == ("ui",)


def installed_matches(deps: set[str], task: dict) -> list[str]:
    hits = [name for name in task["preferred"] if name in deps]
    for prefix in task.get("preferred_prefixes", []):
        hits += sorted(dep for dep in deps if dep.startswith(prefix))
    return hits


def audit(root: Path, max_files: int = 2000) -> dict:
    package = load_json(root / "package.json")
    if package is None:
        raise ValueError(f"{root} has no readable package.json")
    deps = set(package.get("dependencies", {})) | set(package.get("devDependencies", {}))
    components = load_json(root / "components.json")
    ui_dir = None
    if components:
        ui_dir = (components.get("aliases") or {}).get("ui") or "src/components/ui"
        ui_dir = ui_dir.replace("@/", "src/", 1) if ui_dir.startswith("@/") else ui_dir
    files = source_files(root, max_files)
    findings = []
    for task_name, task in TASKS.items():
        pattern = re.compile(task["name_pattern"])
        evidence = []
        for path in files:
            rel = path.relative_to(root)
            if is_vendored(rel, ui_dir):
                continue
            try:
                lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
            except OSError:
                continue
            for number, line in enumerate(lines, 1):
                if pattern.search(line):
                    evidence.append(f"{rel.as_posix()}:{number}")
        preferred_hits = installed_matches(deps, task)
        competitor_hits = [name for name in task["competitors"] if name in deps]
        if not evidence and not competitor_hits:
            continue
        if preferred_hits:
            action = "use-installed"
        elif competitor_hits:
            action = "flag-only"
        else:
            action = "install"
        findings.append(
            {
                "task": task_name,
                "tier": task["tier"],
                "action": action,
                "recommend": task["recommend"],
                "installed": preferred_hits,
                "competitor_installed": competitor_hits,
                "hand_rolled_evidence": evidence[:10],
                "note": {
                    "use-installed": "Route the hand-built code to the installed library.",
                    "flag-only": "A competitor is already a dependency. Say so; do not swap it unless asked.",
                    "install": "Install through the library CLI so the code lands in the project, then build and typecheck.",
                }[action],
            }
        )
    return {
        "project": str(root),
        "react": "react" in deps,
        "shadcn_components_json": components is not None,
        "ui_dir": ui_dir,
        "files_scanned": len(files),
        "findings": findings,
        "limits": "Name and role patterns only. A clean result does not prove no component is hand-built.",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("project", type=Path)
    parser.add_argument("--max-files", type=int, default=2000)
    args = parser.parse_args(argv)
    root = args.project.expanduser().resolve()
    try:
        report = audit(root, args.max_files)
    except ValueError as error:
        print(json.dumps({"error": str(error)}), file=sys.stdout)
        return 2
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
