// Generates src/styles/tokens.css from tokens/design-tokens.json.
// The JSON is the source; never edit the CSS by hand.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(resolve(here, 'design-tokens.json'), 'utf8'));
const out = resolve(here, '../src/styles/tokens.css');

const lines = [];
const push = (s = '') => lines.push(s);

function shadow(layers, scale) {
  return layers
    .map((l) => {
      const a = Math.min(100, +(l.alpha * scale).toFixed(2));
      return `${l.x}px ${l.y}px ${l.blur}px ${l.spread}px color-mix(in srgb, var(--shadow) ${a}%, transparent)`;
    })
    .join(', ');
}

function themeBlock(selector, name, scheme) {
  const scale = name === 'dark' ? t.shadow.darkAlphaScale : 1;
  push(`${selector} {`);
  push(`  color-scheme: ${scheme};`);
  for (const [k, v] of Object.entries(t.color[name])) push(`  --${k}: ${v};`);
  for (const k of ['card', 'low', 'pop', 'sheet']) push(`  --elev-${k}: ${shadow(t.shadow[k], scale)};`);
  push('}');
}

push('/* Generated by tokens/build.mjs from tokens/design-tokens.json. Do not edit. */');
push();
themeBlock(':root', 'light', 'light');
push();
themeBlock(':root[data-theme="dark"]', 'dark', 'dark');
push();

push(':root {');
push('  /* Tiers derived from the foreground colour, shared by both themes. */');
for (const [k, pct] of Object.entries(t.color.tier)) {
  push(`  --${k}: color-mix(in srgb, var(--fg) ${pct}%, transparent);`);
}
push();
push(`  --hairline: ${t.border.hairline}px;`);
push(`  --focus-width: ${t.focus.width}px;`);
push(`  --focus-offset: ${t.focus.offset}px;`);
push(`  --focus-halo: 0 0 0 ${t.focus.haloWidth}px color-mix(in srgb, var(--accent) ${t.focus.haloAlpha}%, transparent);`);
push(`  --press-scale: ${t.press.scale};`);
push();
for (const [k, v] of Object.entries(t.duration)) push(`  --dur-${k}: ${v}ms;`);
push();
for (const [k, v] of Object.entries(t.control)) push(`  --control-${k}: ${v}px;`);
push();
for (const [k, v] of Object.entries(t.z)) push(`  --z-${k}: ${v};`);
push();
for (const [k, v] of Object.entries(t.layout)) if (typeof v === 'number') push(`  --${k}: ${v}px;`);
push('}');
push();

push('@theme {');
push('  --color-*: initial;');
push('  --font-*: initial;');
push('  --text-*: initial;');
push('  --radius-*: initial;');
push('  --shadow-*: initial;');
push('  --ease-*: initial;');
push('  --tracking-*: initial;');
push('  --leading-*: initial;');
push();
push(`  --font-sans: ${t.font.sans};`);
push(`  --font-mono: ${t.font.mono};`);
for (const [k, v] of Object.entries(t.font.weight)) push(`  --font-weight-${k}: ${v};`);
push();
for (const [k, v] of Object.entries(t.type)) {
  push(`  --text-${k}: ${v.size}px;`);
  push(`  --text-${k}--line-height: ${v.line}px;`);
  push(`  --text-${k}--letter-spacing: ${v.tracking};`);
}
push();
for (const [k, v] of Object.entries(t.radius)) push(`  --radius-${k}: ${v}px;`);
push();
for (const [k, v] of Object.entries(t.easing)) push(`  --ease-${k}: ${v};`);
push('}');
push();

push('@theme inline {');
for (const k of Object.keys(t.color.light)) {
  if (k === 'shadow') continue;
  push(`  --color-${k}: var(--${k});`);
}
for (const k of Object.keys(t.color.tier)) push(`  --color-${k}: var(--${k});`);
for (const k of ['card', 'low', 'pop', 'sheet']) push(`  --shadow-${k}: var(--elev-${k});`);
push('}');
push();

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'));
console.log(`tokens: wrote ${out}`);
